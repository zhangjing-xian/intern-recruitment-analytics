/**
 * 隐私页的全部用户可见文案（步骤12，纯常量 + 纯类型，不依赖 React / 存储 / 网络）。
 *
 * 为什么文案要单独一层，而不是直接写在 JSX 里：
 * - 这一页是**对外的事实声明**，每一条都必须能被测试逐字钉住。文案散在 JSX 里就只能靠
 *   「渲染出来的字符串里有没有这几个字」来测，改动一处容易悄悄漏掉一整句；
 * - 三条测试要求（无 Markdown 标记、无过度承诺、必需声明必须出现）都需要能遍历**全部**文案，
 *   因此所有用户可见字符串都从本模块导出，`PrivacyWorkspace.tsx` 只负责摆放，不再新增字面量。
 *
 * 写作纪律（踩过坑，必须遵守）：
 * - **不写 Markdown 标记**：`**加粗**` 在 React 里会原样渲染成星号（前几步就出过这个 bug），
 *   强调一律靠结构（标题 / 列表 / 表格）表达；
 * - **不写过度承诺**：不承诺「绝不会丢」「绝对安全」「不可重新识别」，也不暗示任何找回密码的路径；
 * - **不写营销话术**：只写「代码里现在到底做了什么」，凡是浏览器（配额、回收、无痕模式）决定的事，
 *   一律写明「由浏览器决定」，不替浏览器担保。
 */

